#!/usr/bin/env bash
# Write configuration-hackage2nix/compiler.yaml: the compiler and the core
# (GHC-bundled) packages of the compiler named in compiler.nix. hackage2ekapkgs uses this to
# avoid generating packages that ship with the compiler.
#
# Re-run whenever compiler.nix changes;
# scripts/regenerate-hackage-packages.sh refuses to run on a mismatch.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO_ROOT"

ghc="$(nix-build --no-out-link -E '(import ./. { }).haskell.compiler.${import ./compiler.nix}')"
version="$("$ghc/bin/ghc" --numeric-version)"

{
  echo "# Generated by scripts/generate-compiler-config.sh -- DO NOT EDIT MANUALLY!"
  echo "compiler: ghc-$version"
  echo ""
  echo "core-packages:"
  "$ghc/bin/ghc-pkg" list --global --simple-output |
    tr ' ' '\n' | sed -e '/^$/d' -e 's/^/  - /' | LC_ALL=C sort
} > configuration-hackage2nix/compiler.yaml

echo "Wrote configuration-hackage2nix/compiler.yaml for ghc-$version"
